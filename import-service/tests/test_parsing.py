import pytest

import parsing
from helpers import xlsx


def student_ids(content, file_name):
    rows = parsing.read_rows(content, file_name)
    return parsing.extract(rows, parsing.STUDENT_ID_COLUMNS)


def test_numeric_ids_from_excel_keep_their_row_numbers():
    content = xlsx({"Sheet1": [["studentId"], [9900000001], [9900000002.0]]})
    rows = student_ids(content, "shortlist.xlsx")
    assert [number for number, _ in rows] == [2, 3]
    assert [record["studentId"] for _, record in rows] == [9900000001, 9900000002]


def test_header_not_on_row_1():
    content = xlsx({"Sheet1": [
        ["Acme Corp shortlist"],
        [],
        ["Generated by the placement cell"],
        ["S.No", "Reg No"],
        [1, 9900000001],
        [2, 9900000002],
    ]})
    rows = student_ids(content, "shortlist.xlsx")
    assert rows == [(5, {"studentId": 9900000001}), (6, {"studentId": 9900000002})]


def test_header_beyond_row_10_is_not_found():
    content = xlsx({"Sheet1": [["note"]] * 10 + [["studentId"], [9900000001]]})
    with pytest.raises(parsing.ParseError, match="Header row not found"):
        student_ids(content, "shortlist.xlsx")


@pytest.mark.parametrize("header", [
    "studentId", "Student ID", "student_id", "ID", "Reg No", "REG_NO",
    "Registration Number", "roll no", " Roll_No ",
])
def test_student_id_header_aliases(header):
    content = xlsx({"Sheet1": [[header], [9900000001]]})
    assert student_ids(content, "shortlist.xlsx") == [(2, {"studentId": 9900000001})]


def test_fully_empty_rows_are_ignored_but_still_counted_for_row_numbers():
    content = xlsx({"Sheet1": [
        ["studentId", "name"],
        [9900000001, "A"],
        [None, None],
        ["   ", None],
        [9900000002, "B"],
        [None, "name but no id"],
    ]})
    rows = student_ids(content, "shortlist.xlsx")
    assert [number for number, _ in rows] == [2, 5, 6]
    assert parsing.is_empty(rows[-1][1]["studentId"])


def test_csv_with_title_row_and_blank_lines():
    content = b"Attendance for session 7\r\n\r\nstudent id,name\r\n9900000001,A\r\n\r\n9900000002,B\r\n"
    rows = student_ids(content, "attendance.csv")
    assert rows == [(4, {"studentId": "9900000001"}), (6, {"studentId": "9900000002"})]


def test_csv_with_utf8_bom():
    content = "﻿studentId\n9900000001\n".encode("utf-8")
    assert student_ids(content, "a.csv") == [(2, {"studentId": "9900000001"})]


def test_timetable_sheets_are_found_by_name():
    content = xlsx({
        "Slots": [["Section Code", "Course Name", "Day Of Week", "Start Time", "End Time", "Room"],
                  ["S12", "Cloud Native", "MONDAY", "10:00", "10:50", "C-301"]],
        "ENROLMENTS": [["student_id", "section_code"], [9900000001, "S12"]],
    })
    slots = parsing.extract(parsing.read_rows(content, "t.xlsx", "slots"), parsing.SLOT_COLUMNS)
    enrolments = parsing.extract(
        parsing.read_rows(content, "t.xlsx", "enrolments"), parsing.ENROLMENT_COLUMNS)
    assert slots[0][1]["room"] == "C-301"
    assert enrolments == [(2, {"studentId": 9900000001, "sectionCode": "S12"})]


def test_missing_sheet():
    content = xlsx({"slots": [["sectionCode"]]})
    with pytest.raises(parsing.ParseError, match="Sheet 'enrolments' not found"):
        parsing.read_rows(content, "t.xlsx", "enrolments")


def test_csv_cannot_be_a_timetable():
    with pytest.raises(parsing.ParseError, match="upload an .xlsx file"):
        parsing.read_rows(b"studentId,sectionCode\n", "t.csv", "enrolments")


@pytest.mark.parametrize("file_name", ["list.xls", "list.pdf", "list", "list.xlsx.exe"])
def test_other_file_types_are_refused(file_name):
    with pytest.raises(parsing.ParseError, match="only .xlsx and .csv"):
        parsing.check_file(file_name, b"data")


def test_file_over_5_mb_is_refused():
    with pytest.raises(parsing.ParseError, match="maximum size is 5 MB"):
        parsing.check_file("list.csv", b"x" * (5 * 1024 * 1024 + 1))
    assert parsing.check_file("LIST.CSV", b"x" * (5 * 1024 * 1024)) == ".csv"


def test_corrupt_xlsx():
    with pytest.raises(parsing.ParseError, match="not a valid .xlsx"):
        parsing.read_rows(b"this is not a zip file", "list.xlsx")
